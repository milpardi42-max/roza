export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function productsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

export function productsByPattern(patternSlug: string): Product[] {
  return products.filter((p) => p.patternSlug === patternSlug);
}

export function productsByArtist(artistSlug: string): Product[] {
  return products.filter((p) => p.artistSlug === artistSlug);
}

export function relatedProducts(slug: string, limit = 4): Product[] {
  const origin = getProduct(slug);
  if (!origin) return products.slice(0, limit);
  return products
    .filter((p) => p.slug !== slug)
    .sort(
      (a, b) =>
        (b.categorySlug === origin.categorySlug ? 1 : 0) -
        (a.categorySlug === origin.categorySlug ? 1 : 0)
    )
    .slice(0, limit);
}
